// Builds all audio for the episode and the timeline the composition reads.
// 1. Kokoro TTS (via `npx hyperframes tts`) per line, cached by hash
// 2. Per-character voice FX (pitch/tempo, trim, loudnorm)
// 3. Timeline from measured durations + per-frame mouth envelopes
// 4. Synthesized BGM bed + SFX (bundled HyperFrames library + ffmpeg-synthesized cartoon cues)
// 5. Master mix: voices + sidechain-ducked BGM + SFX -> assets/audio/mix.wav
// Output: assets/audio/mix.wav, src/episode-data.js (window.EPISODE)
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Z]:)/, '$1')), '..');
const ep = JSON.parse(fs.readFileSync(path.join(ROOT, 'episode.json'), 'utf8'));
const WORK = path.join(ROOT, '.build', 'audio');
const OUT = path.join(ROOT, 'assets', 'audio');
fs.mkdirSync(WORK, { recursive: true });
fs.mkdirSync(OUT, { recursive: true });

const FPS = 30;
const RATE = 48000;
const LEAD_IN = 0.45;
const GAP = 0.3;
const TAIL = 1.4;
const BUNDLED_SFX = 'C:/Users/pmluis/.claude/plugins/cache/claude-plugins-official/hyperframes/0.8.61/skills/media-use/audio/assets/sfx';

// Kokoro voice + post FX per character.
const VOICES = {
  profe: { voice: 'em_alex', speed: 0.95, pitch: 0.93, tempo: 1.0 }, // mature, calm
  tito: { voice: 'ef_dora', speed: 1.08, pitch: 1.14, tempo: 1.04 }, // young, energetic
};

const sh = (cmd, args) => execFileSync(cmd, args, { stdio: ['ignore', 'pipe', 'pipe'], shell: cmd === 'npx' }).toString();
const ff = (args) => sh('ffmpeg', ['-y', '-v', 'error', ...args]);
const dur = (f) => Number(sh('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', f]).trim());

function readPcm(file) {
  const buf = execFileSync('ffmpeg', ['-v', 'error', '-i', file, '-f', 's16le', '-ac', '1', '-ar', String(RATE), '-']);
  const out = new Float32Array(buf.length / 2);
  for (let i = 0; i < out.length; i++) out[i] = buf.readInt16LE(i * 2) / 32768;
  return out;
}

function envelope(samples) {
  const step = RATE / FPS;
  const env = [];
  for (let i = 0; i * step < samples.length; i++) {
    let s = 0, n = 0;
    for (let j = Math.floor(i * step); j < Math.min(samples.length, (i + 1) * step); j++) { s += samples[j] ** 2; n++; }
    env.push(Math.sqrt(s / Math.max(1, n)));
  }
  const peak = Math.max(...env, 1e-6);
  return env.map((v) => Math.round(Math.min(1, Math.max(0, (v / peak - 0.08) * 1.5)) * 100) / 100);
}

// ---------- 1+2. voices ----------
const voiceFiles = ep.lines.map((line, i) => {
  const v = VOICES[line.speaker];
  const say = line.say ?? line.text;
  const hash = crypto.createHash('sha1').update(JSON.stringify([say, v])).digest('hex').slice(0, 10);
  const raw = path.join(WORK, `line${String(i + 1).padStart(2, '0')}-${hash}.raw.wav`);
  const fx = path.join(WORK, `line${String(i + 1).padStart(2, '0')}-${hash}.wav`);
  if (!fs.existsSync(raw)) {
    console.log(`tts ${i + 1}/${ep.lines.length} ${line.speaker}`);
    sh('npx', ['hyperframes', 'tts', JSON.stringify(say), '-v', v.voice, '-l', 'es', '-s', String(v.speed), '-o', JSON.stringify(raw)]);
  }
  if (!fs.existsSync(fx)) {
    const src = 24000;
    const af = [
      'silenceremove=start_periods=1:start_threshold=-45dB',
      'areverse', 'silenceremove=start_periods=1:start_threshold=-45dB', 'areverse',
      `asetrate=${Math.round(src * v.pitch)}`, `aresample=${RATE}`, `atempo=${(v.tempo / v.pitch).toFixed(4)}`,
      'highpass=f=90', 'equalizer=f=3500:t=q:w=1:g=2', 'loudnorm=I=-16:TP=-1.5:LRA=7', `aresample=${RATE}`,
    ].join(',');
    ff(['-i', raw, '-af', af, '-ac', '1', '-ar', String(RATE), '-c:a', 'pcm_s16le', fx]);
  }
  return fx;
});

// ---------- 3. timeline ----------
let t = LEAD_IN;
const lines = ep.lines.map((line, i) => {
  const d = dur(voiceFiles[i]);
  const entry = {
    i, speaker: line.speaker, text: line.text, shot: line.shot ?? null, board: line.board ?? null,
    emotion: line.emotion ?? null, dutch: !!line.dutch, start: +t.toFixed(3), end: +(t + d).toFixed(3),
    envFps: FPS, env: envelope(readPcm(voiceFiles[i])), sfx: line.sfx ?? [],
  };
  t += d + GAP + (line.board ? 0.25 : 0);
  return entry;
});
const duration = +(lines.at(-1).end + TAIL).toFixed(3);
fs.writeFileSync(path.join(ROOT, 'src', 'episode-data.js'),
  `// Generated by scripts/build-audio.mjs. Do not edit.\nwindow.EPISODE = ${JSON.stringify({ id: ep.id, duration, fps: FPS, lines })};\n`);
console.log(`timeline: ${lines.length} lines, ${duration}s`);

// ---------- 4. BGM + SFX ----------
const music = path.join(WORK, 'music.wav');
{
  // Light pizzicato-ish arpeggio (C major pentatonic, I-vi-IV-V), 0.25 s steps, with a soft bass pulse.
  const notes = [261.63, 329.63, 392.0, 523.25, 220.0, 261.63, 329.63, 440.0, 174.61, 220.0, 261.63, 349.23, 196.0, 246.94, 293.66, 392.0];
  const k = 'mod(floor(t*4),16)';
  let f = String(notes.at(-1));
  for (let i = notes.length - 2; i >= 0; i--) f = `if(eq(${k},${i}),${notes[i]},${f})`;
  const env = 'exp(-9*mod(t,0.25))';
  const bass = 'if(lt(mod(t,4),1),65.41,if(lt(mod(t,4),2),55.0,if(lt(mod(t,4),3),43.65,49.0)))';
  const expr = `0.2*${env}*(sin(2*PI*(${f})*t)+0.25*sin(4*PI*(${f})*t))+0.12*exp(-4*mod(t,0.5))*sin(2*PI*(${bass})*t)`;
  ff(['-f', 'lavfi', '-i', `aevalsrc='${expr}':s=${RATE}:d=${duration.toFixed(3)}`, '-af',
    `lowpass=f=3000,aecho=0.8:0.5:120:0.25,afade=t=in:d=0.8,afade=t=out:st=${(duration - 1.6).toFixed(2)}:d=1.6`,
    '-ac', '1', '-c:a', 'pcm_s16le', music]);
}

const SYNTH = {
  // cartoon spring: falling-then-wobbling sine
  boing: "aevalsrc='0.6*exp(-5*t)*sin(2*PI*(180+120*exp(-6*t)*cos(2*PI*9*t))*t)':s=48000:d=0.7",
  // rabbit squeak: fast rising chirp
  squeak: "aevalsrc='0.4*sin(PI*t/0.18)*sin(2*PI*(1800+2600*t/0.18)*t)':s=48000:d=0.18",
  // carriage: galloping hoof clicks (3-beat pattern) over a wheel rumble
  hooves: "aevalsrc='0.7*exp(-60*mod(t,0.12))*(lt(mod(t,0.48),0.36))*sin(2*PI*240*t)+0.08*sin(2*PI*55*t)*sin(2*PI*7*t)':s=48000:d=1.6",
};
function sfxFile(name) {
  const out = path.join(WORK, `sfx-${name}.wav`);
  if (fs.existsSync(out)) return out;
  if (SYNTH[name]) ff(['-f', 'lavfi', '-i', SYNTH[name], '-ac', '1', '-c:a', 'pcm_s16le', out]);
  else ff(['-i', path.join(BUNDLED_SFX, `${name}.mp3`), '-ac', '1', '-ar', String(RATE), '-c:a', 'pcm_s16le', out]);
  return out;
}

// ---------- 5. mix ----------
const inputs = [];
const filters = [];
const voiceLabels = [];
lines.forEach((l, i) => {
  inputs.push('-i', voiceFiles[i]);
  const ms = Math.round(l.start * 1000);
  filters.push(`[${inputs.length / 2 - 1}:a]adelay=${ms}|${ms},apad=whole_dur=${duration}[v${i}]`);
  voiceLabels.push(`[v${i}]`);
});
filters.push(`${voiceLabels.join('')}amix=inputs=${voiceLabels.length}:normalize=0,asplit=2[vox][key]`);
inputs.push('-i', music);
const mIdx = inputs.length / 2 - 1;
filters.push(`[${mIdx}:a]volume=0.55[bgm0]`, '[bgm0][key]sidechaincompress=threshold=0.02:ratio=8:attack=40:release=400[bgm]');
const sfxLabels = [];
lines.forEach((l) => l.sfx.forEach(([name, off]) => {
  inputs.push('-i', sfxFile(name));
  const idx = inputs.length / 2 - 1;
  const ms = Math.round((l.start + off) * 1000);
  const vol = { whoosh: 0.35, pop: 0.45, squeak: 0.3, boing: 0.35, hooves: 0.35 }[name] ?? 0.35;
  filters.push(`[${idx}:a]volume=${vol},adelay=${ms}|${ms},apad=whole_dur=${duration}[s${idx}]`);
  sfxLabels.push(`[s${idx}]`);
}));
filters.push(`[vox][bgm]${sfxLabels.join('')}amix=inputs=${2 + sfxLabels.length}:normalize=0,atrim=0:${duration},loudnorm=I=-14:TP=-1.5:LRA=9,aresample=${RATE}[out]`);
const mix = path.join(OUT, 'mix.wav');
ff([...inputs, '-filter_complex', filters.join(';'), '-map', '[out]', '-ac', '2', '-ar', String(RATE), '-c:a', 'pcm_s16le', mix]);
console.log(`mix: ${mix} (${dur(mix).toFixed(2)}s)`);

// Keep the composition's root and audio durations in sync with the measured timeline.
const indexFile = path.join(ROOT, 'index.html');
fs.writeFileSync(indexFile, fs.readFileSync(indexFile, 'utf8').replace(/data-duration="[\d.]+"/g, `data-duration="${duration}"`));
console.log(`index.html duration -> ${duration}s`);
